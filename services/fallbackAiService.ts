// This file contains non-AI based fallbacks for generating content when offline.

interface CommentContext {
    studentName: string;
    performanceSummary: string;
    // Future context can be added here, e.g., subjectName, score
}

export const generateFallbackComment = (context: CommentContext): string => {
    const { studentName, performanceSummary } = context;
    const performanceLower = performanceSummary.toLowerCase();
    
    let opening = `${studentName} has demonstrated a positive attitude towards learning.`;
    let detail = '';
    let recommendation = 'Continued effort will surely yield even better results.';

    // Analyze performance summary for keywords
    if (performanceLower.includes('excellent') || performanceLower.includes('strong') || performanceLower.includes('very good')) {
        opening = `${studentName} has shown excellent performance this term.`;
        detail = 'He/She consistently submits high-quality work and actively participates in class discussions.';
        recommendation = 'Keep up the fantastic work!';
    } else if (performanceLower.includes('good') || performanceLower.includes('steady progress')) {
        opening = `${studentName} is making steady progress.`;
        detail = 'He/She grasps new concepts well with consistent effort.';
    } else if (performanceLower.includes('struggles') || performanceLower.includes('difficulty') || performanceLower.includes('weak')) {
        opening = `${studentName} shows potential but is facing some challenges.`;
        detail = 'He/She sometimes struggles with new topics but is encouraged to ask more questions in class.';
        recommendation = 'With increased focus and consistent practice, improvement is definitely achievable.';
    } else if (performanceLower.includes('improvement')) {
        opening = `${studentName} has shown commendable improvement this term.`;
        detail = 'His/Her hard work is beginning to pay off, which is wonderful to see.';
    }

    return [opening, detail, recommendation].filter(Boolean).join(' ');
};

