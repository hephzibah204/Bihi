export const getFallbackChatResponse = (prompt: string): string => {
    const p = prompt.toLowerCase();
    if (p.includes('add') && (p.includes('student') || p.includes('teacher'))) {
        return "To add a new student or teacher, please navigate to the 'Students' or 'Teachers' page from the main menu and click the 'Add' button.";
    }
    if (p.includes('score') || p.includes('result')) {
        return "You can enter student scores on the 'Enter Scores' page, accessible from the 'Academics' section in the sidebar.";
    }
    if (p.includes('report card')) {
        return "Report cards can be generated, viewed, and printed from the 'Report Cards' page in the 'Academics' section.";
    }
    if (p.includes('timetable') || p.includes('schedule')) {
        return "The school timetable can be managed from the 'Timetable' page. You can view your personal schedule as a teacher from your dashboard.";
    }
    return "I have limited functionality while offline. I can only answer basic questions about navigating the app. Please connect to the internet for full assistance.";
};

